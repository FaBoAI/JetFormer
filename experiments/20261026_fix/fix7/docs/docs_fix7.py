def apply_text(texts):
    out = dict(texts)
    rep = []
    for f, edits in ALL:
        t = out[f]
        for old, new in edits:
            n_old, n_new = t.count(old), t.count(new)
            if n_old == 1 and n_new == 0:
                t = t.replace(old, new)
                rep.append((f, old, 'apply'))
            elif n_old == 0 and n_new >= 1:
                rep.append((f, old, 'done'))
            elif n_old == 1 and n_new >= 1 and old in new:          # 足す形: 入れたあとも old は new の中に残る
                rep.append((f, old, 'done'))
            else:
                rep.append((f, old, 'missing' if n_old == 0 else 'many(%d)' % n_old))
        out[f] = t
    return out, rep


