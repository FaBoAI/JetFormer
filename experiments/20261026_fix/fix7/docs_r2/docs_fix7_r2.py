def r1_intact(texts):
    """7-1 回目の 44 個の直しが、どれも「済」で、new の文がちょうど 1 回ある(この組が 7-1 回目の文を壊していない)"""
    m = r1()
    _, rep = m.apply_text(texts)
    bad = [(f, o[:30], s) for f, o, s in rep if s != 'done']
    for f, edits in m.ALL:
        for old, new in edits:
            if texts[f].count(new) != 1:
                bad.append((f, new[:30], 'count %d' % texts[f].count(new)))
    m9 = m.ban9()
    b9 = {f: texts.get(f, (REPORTS / f).read_text(encoding='utf-8')) for f in m9.FILES}
    _, rep9 = m9.apply_text(b9)
    bad += [(f, o[:30], 'ban9 ' + s) for f, o, s in rep9 if s != 'done']
    bad += [('ban9 stale', str(x)[:40], '') for x in m9.stale(b9, m9.versions()[0])]
    return bad


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--apply', action='store_true')
    ap.add_argument('--from-bak', action='store_true',
                    help='直す前の控え(*%s)から直し直す。今の文書が FIRST_APPLY の sha256(この台本の前の版で書いたもの)のときだけ' % BAK)
    a = ap.parse_args(argv)
    texts = {f: (REPORTS / f).read_text(encoding='utf-8') for f, _ in ALL}
    if a.from_bak:
        changed = [f for f in texts if hashlib.sha256(texts[f].encode('utf-8')).hexdigest() not in FIRST_APPLY[f]]
        if changed:
            print('前の版で書いたあとに変わった文書があるので、控えからは直し直しません: %s' % changed)
            return 1
        texts = {f: (REPORTS / (f + BAK)).read_text(encoding='utf-8') for f, _ in ALL}
    new, rep = apply_text(texts)
    bad = [(f, o, s) for f, o, s in rep if s not in ('apply', 'done')]
    for f, o, s in rep:
        print('%-8s %s「%s…」' % (s, f, o[:36].replace('\n', '⏎')))
    for f, _ in ALL:
        if new[f] != texts[f]:
            sys.stdout.writelines(difflib.unified_diff(texts[f].splitlines(True), new[f].splitlines(True), f, f + '(fix7 r2)', n=0))
    br1 = r1_intact(new)
    print('7-1 回目の直し・画面の版 9: 済でないもの %d' % len(br1))
    for x in br1:
        print('  ', x)
    ok = not bad and not br1
    if a.apply and ok:
        cur = {f: (REPORTS / f).read_text(encoding='utf-8') for f, _ in ALL}
        for f, _ in ALL:
            if new[f] != cur[f]:
                p = REPORTS / f
                if not p.with_name(p.name + BAK).exists():
                    print('控えが無いので書きません: %s' % p)
                    return 1
        for f, _ in ALL:
            if new[f] != cur[f]:
                (REPORTS / f).write_text(new[f], encoding='utf-8')
                print('書いた: %s' % (REPORTS / f))
    elif a.apply:
        print('当たらない直しがあるので書きません: %s' % [(f, o[:30], s) for f, o, s in bad])
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
